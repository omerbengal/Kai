CREATE_NO_WINDOW = 0x08000000


class Paths:
    def __init__(self, bot, home=None):
        self.bot = bot
        if home is None:
            import kai_bots
            home = kai_bots.bot(bot)["home"]
        self.dir = os.path.join(home, "tmp")
        self.lease = os.path.join(self.dir, "typing_lease.json")
        self.lock = self.lease + ".lock"
        self.inflight = os.path.join(self.dir, "typing_inflight.txt")
        self.last_send = os.path.join(self.dir, "typing_last_send.txt")
        self.trace = os.path.join(self.dir, "typing_trace.log")


def _tlog(p, event, extra=""):
    try:
        import datetime
        with open(p.trace, "a", encoding="utf-8") as f:
            f.write("{}  {:<12} {}\n".format(datetime.datetime.now().strftime("%H:%M:%S.%f")[:-3], event, extra))
    except Exception:
        pass


def _read(p):
    try:
        with open(p.lease, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


def _write(p, lease):
    os.makedirs(p.dir, exist_ok=True)
    tmp = p.lease + ".%d.tmp" % os.getpid()
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(lease, f)
    os.replace(tmp, p.lease)


class _Lock:
    """O_EXCL lock file; stale after 2s; gives up after 1s (typing must never block a tool)."""
    def __init__(self, p):
        self.path, self.fd = p.lock, None
        os.makedirs(p.dir, exist_ok=True)

    def __enter__(self):
        end = time.time() + 1.0
        while True:
            try:
                self.fd = os.open(self.path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                return self
            except FileExistsError:
                try:
                    if time.time() - os.path.getmtime(self.path) > 2:
                        os.remove(self.path)
                        continue
                except Exception:
                    pass
                if time.time() > end:
                    return self
                time.sleep(0.02)
            except Exception:
                return self

    def __exit__(self, *a):
        if self.fd is not None:
            try:
                os.close(self.fd)
                os.remove(self.path)
            except Exception:
                pass


def _alive(pid):
    try:
        import psutil
        return psutil.pid_exists(int(pid))
    except Exception:
        return False


def _spawn_loop(p):
    proc = subprocess.Popen(
        [sys.executable, os.path.abspath(__file__), "loop", "--bot", p.bot],
        creationflags=DETACHED_PROCESS | CREATE_NEW_PROCESS_GROUP | CREATE_NO_WINDOW,
        close_fds=True, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return proc.pid


def _ensure_loop(p, lease, spawn):
    if lease.get("pid") and _alive(lease["pid"]):
        return lease
    lease["pid"] = spawn(p)
    return lease


def _tasks(lease, now=None):
    """Open tasks, without the ones older than TASK_TTL."""
    now = now or time.time()
    t = lease.get("tasks") or {}
    return {k: v for k, v in t.items()
            if now - max(float(v.get("opened", 0) or 0), float(v.get("bg", 0) or 0))
            < (TASK_TTL if v.get("ack") else NOACK_TTL)}


def _bg_tasks(lease, now=None):
    """Open tasks whose worker is waiting on a background process it launched less than BG_HOLD ago."""
    now = now or time.time()
    return {k: v for k, v in _tasks(lease, now).items()
            if v.get("bg") and now - float(v["bg"]) < BG_HOLD}


def call_cap(tool_name, tool_input):
    """Seconds an open call may keep typing: its own timeout (ms param, shells only) + CALL_MARGIN."""
    t = (tool_input or {}).get("timeout") if tool_name in BG_SHELLS else None
    try:
        secs = min(max(float(t) / 1000.0, 1), CALL_MAX) if t else CALL_DEFAULT
    except (TypeError, ValueError):
        secs = CALL_DEFAULT
    return secs + CALL_MARGIN


def _open_calls(lease, now=None):
    now = now or time.time()
    return {k: v for k, v in (lease.get("calls") or {}).items()
            if now < float(v.get("until", 0) or 0)}


def open_call(p, call_id, tool_name, tool_input):
    """PreToolUse: remember a foreground call until its Post (or its cap). Never opens the lease."""
    if not call_id or tool_name in SKIP_TOOLS or is_bg_call(tool_name, tool_input):
        return False
    now = time.time()
    with _Lock(p):
        lease = _read(p)
        if not lease or not lease.get("turn_open") or call_id in (lease.get("closed") or []):
            return False
        calls = _open_calls(lease, now)
        calls[call_id] = {"tool": tool_name, "start": now, "until": now + call_cap(tool_name, tool_input)}
        lease["calls"] = calls
        _write(p, lease)
    return True


def close_call(p, call_id):
    """PostToolUse / PostToolUseFailure: the call is over."""
    if not call_id:
        return
    now = time.time()
    with _Lock(p):
        lease = _read(p)
        if not lease:
            return
        calls = _open_calls(lease, now)
        calls.pop(call_id, None)
        lease["calls"] = calls
        lease["closed"] = ((lease.get("closed") or []) + [call_id])[-CLOSED_KEEP:]
        lease["last_activity"] = now   # the call just ended: the usual window starts from here
        _write(p, lease)


def _keepalive(lease, now=None):
    now = now or time.time()
    if _bg_tasks(lease, now):
        return True
    if _tasks(lease, now) and _open_calls(lease, now):
        return True   # a long foreground call (flutter build) is still running
    return bool(_tasks(lease, now)) and now - float(lease.get("last_activity", 0) or 0) < ACTIVITY_WINDOW


def is_bg_call(tool_name, tool_input):
    """A tool call after which the worker may end its turn and wait: a background shell, or Monitor."""
    ti = tool_input or {}
    if tool_name in BG_SHELLS:
        return bool(ti.get("run_in_background"))
    return tool_name in BG_WAIT_TOOLS


def _worker_ack(p, agent_id, transcript_path=None, session_id=None):
    """The ACK id of the worker that made the call, from bots/ack_live.py's state (agent -> ACK), else its
    transcript's task block. None when unknown (the dispatcher's own call, or ack_live has no entry)."""
    if not agent_id:
        return None
    try:
        import ack_live
        ack = ack_live.load(p.dir)["agents"].get(agent_id)
        if not ack:
            ack = ack_live.block_from_transcript(
                ack_live.agent_transcript(transcript_path, session_id, agent_id))[0]
        return str(ack) if ack else None
    except Exception:
        return None


def mark_bg(p, agent_id=None, transcript_path=None, session_id=None, spawn=_spawn_loop, ack=None):
    """A background launch: stamp the caller's task (by its ACK) "bg". Unknown ACK = every open task that
    has an ACK (each still ends on its own ACK delete). Returns the stamped msg ids."""
    ack = ack or _worker_ack(p, agent_id, transcript_path, session_id)
    now = time.time()
    with _Lock(p):
        lease = _read(p)
        if not lease or not lease.get("turn_open"):
            return []
        tasks = _tasks(lease, now)
        # the caller's own task counts even past TASK_TTL: its worker is alive, it just made this call
        raw = lease.get("tasks") or {}
        hit = [k for k, v in raw.items() if ack and str(v.get("ack")) == ack]
        for k in hit:
            tasks[k] = raw[k]
        if not hit:
            hit = [k for k, v in tasks.items() if v.get("ack") not in (None, "", "pending")]
        for k in hit:
            tasks[k]["bg"] = now
        lease["tasks"] = tasks
        if hit:
            lease = _ensure_loop(p, lease, spawn)
        _write(p, lease)
    _tlog(p, "BG", f"ack={ack} agent={agent_id} tasks={','.join(hit) or '-'}")
    return hit


def _resume(p, lease, spawn, now):
    tasks = _tasks(lease, now)
    if tasks:   # type where a still-open task lives (the newest one)
        last = max(tasks.values(), key=lambda v: float(v.get("opened", 0) or 0))
        if last.get("chat_id"):
            lease["chat_id"], lease["thread_id"] = last.get("chat_id"), last.get("thread_id")
    lease["paused_at"] = 0
    lease["last_activity"] = now
    lease["deadline"] = max(float(lease.get("deadline", 0) or 0), now + LEASE_SECONDS)
    return _ensure_loop(p, lease, spawn)


def open_lease(p, chat_id, thread_id=None, spawn=_spawn_loop, msg_id=None):
    """Incoming message: the ONLY thing that opens the indicator (and clears a pause). Opens a task."""
    now = time.time()
    with _Lock(p):
        old = _read(p) or {}
        tasks = _tasks(old, now)
        if msg_id:
            prev = tasks.get(str(msg_id), {})
            tasks[str(msg_id)] = {"chat_id": str(chat_id), "thread_id": str(thread_id) if thread_id else None,
                                  "opened": now, "ack": prev.get("ack")}
        lease = {"chat_id": str(chat_id), "thread_id": str(thread_id) if thread_id else None,
                 "deadline": now + LEASE_SECONDS, "turn_open": True, "pid": old.get("pid", 0),
                 "paused_at": 0, "last_activity": now, "tasks": tasks}
        lease = _ensure_loop(p, lease, spawn)
        _write(p, lease)
    _tlog(p, "OPEN", f"chat={chat_id} thread={thread_id} msg={msg_id} tasks={len(tasks)}")


ACK_PREFIXES = ("🔄", "🎤 מתמלל")
RTL_MARKS = chr(0x200F) + chr(0x200E)


def is_ack_text(text):
    """True for a status ACK ("🔄 ..." / "🎤 מתמלל..."), the message a dispatcher sends when the auto-ACK failed."""
    t = (text or "").lstrip(RTL_MARKS + " \n")
    return t.startswith(ACK_PREFIXES)


def attach_manual_ack(p, msg_id, ack_id):
    """A manual ACK reply was sent: attach it only to a task that has no real ACK yet (never replace one)."""
    with _Lock(p):
        lease = _read(p)
        t = ((lease or {}).get("tasks") or {}).get(str(msg_id))
        if t is None or t.get("ack") not in (None, "", "pending"):
            return False
        t["ack"] = str(ack_id)
        _write(p, lease)
    _tlog(p, "ACK-MANUAL", f"msg={msg_id} ack={ack_id}")
    return True


def attach_ack(p, msg_id, ack_id):
    """auto-ACK sent: remember which ACK belongs to which task (its delete ends the task)."""
    with _Lock(p):
        # no lease yet: the async open hook may still be running (it keeps this entry), or the bot has no
        # typing hooks at all - turn_open False, so nothing can start typing from here
        lease = _read(p) or {"tasks": {}, "deadline": 0, "turn_open": False, "pid": 0, "paused_at": 0}
        tasks = lease.setdefault("tasks", {})
        t = tasks.setdefault(str(msg_id), {"opened": time.time()})
        t["ack"] = str(ack_id)
        _write(p, lease)


def end_task(p, ack_id=None, msg_id=None, spawn=_spawn_loop):
    """A task finished (its ACK deleted, or a reply to a task with no ACK). Typing resumes at once if
    another task is still open. Returns the number of tasks left."""
    now = time.time()
    with _Lock(p):
        lease = _read(p)
        if not lease:
            return 0
        tasks = _tasks(lease, now)
        gone = [k for k, v in tasks.items()
                if (ack_id and str(v.get("ack")) == str(ack_id)) or (msg_id and k == str(msg_id))]
        if not gone:
            return len(tasks)
        for k in gone:
            tasks.pop(k, None)
        lease["tasks"] = tasks
        if tasks and lease.get("turn_open"):
            lease = _resume(p, lease, spawn, now)
        _write(p, lease)
    _tlog(p, "TASK-END", f"ack={ack_id} msg={msg_id} left={len(tasks)}")
    return len(tasks)


def renew(p, hold=LEASE_SECONDS, spawn=_spawn_loop):
    """Extend an open lease. Never opens one; never revives a pause younger than RESUME_GRACE."""
    now = time.time()
    with _Lock(p):
        lease = _read(p)
        if not lease or not lease.get("turn_open"):
            return False
        lease["last_activity"] = now
        paused_at = float(lease.get("paused_at", 0) or 0)
        # another task still open = the pause was for another task's reply: short grace only
        grace = PAUSE_RESUME if _tasks(lease, now) else RESUME_GRACE
        if paused_at and now - paused_at < grace:
            _write(p, lease)
            return False
        lease = _resume(p, lease, spawn, now)
        lease["deadline"] = max(float(lease.get("deadline", 0) or 0), now + hold)
        _write(p, lease)
        return True


def _last_send(p):
    try:
        with open(p.last_send, encoding="utf-8") as f:
            return float(f.read().strip() or 0)
    except Exception:
        return 0.0


def pause(p, wait_expire=False, reply_to=None, text=None):
    """Before a reply / react: typing off now; returns after any in-flight sendChatAction landed.
    A reply to a task that has no ACK (trivial / inline) is that task's end - unless the reply IS its ACK
    (a manual one after a failed auto-ACK): then the task stays, ack "pending" until the save hook attaches it."""
    had = False
    with _Lock(p):
        lease = _read(p)
        if lease:
            had = True
            lease["deadline"] = 0
            lease["paused_at"] = time.time()
            if reply_to:
                t = (lease.get("tasks") or {}).get(str(reply_to))
                if t is not None and not t.get("ack"):
                    if is_ack_text(text):
                        t["ack"] = "pending"
                    else:
                        lease["tasks"].pop(str(reply_to), None)
            _write(p, lease)
    end = time.time() + INFLIGHT_WAIT
    while time.time() < end:
        try:
            if time.time() - os.path.getmtime(p.inflight) > INFLIGHT_WAIT + 1:
                break
        except Exception:
            break
        time.sleep(0.02)
    if wait_expire and had:
        remaining = _last_send(p) + TYPING_VISIBLE - time.time()
        if remaining > 0:
            time.sleep(min(remaining, TYPING_VISIBLE))
    _tlog(p, "PAUSE", "react" if wait_expire else "")


def _loop_state(p, my_pid):
    """(state, lease): "send", "wait" (a background task holds the loop through a reply's pause), or None."""
    lease = _read(p)
    if not lease or int(lease.get("pid", 0) or 0) != my_pid:
        return None, None
    now = time.time()
    if float(lease.get("deadline", 0) or 0) > now:
        return "send", lease
    paused_at = float(lease.get("paused_at", 0) or 0)
    if not paused_at and _keepalive(lease, now):
        return "send", lease   # open tasks: a long tool call, or a worker waiting on a background process
    if paused_at and _bg_tasks(lease, now):
        return ("send" if now - paused_at >= PAUSE_RESUME else "wait"), lease
    return None, None


def _lease_alive(p, my_pid):
    state, lease = _loop_state(p, my_pid)
    return lease if state == "send" else None


def send_typing(p, chat_id, thread_id=None):
    import bot_tg
    params = {"chat_id": chat_id, "action": "typing"}
    if thread_id:
        params["message_thread_id"] = thread_id
    url = f"https://api.telegram.org/bot{bot_tg.token(p.bot)}/sendChatAction"
    try:
        with urllib.request.urlopen(url, data=urllib.parse.urlencode(params).encode(), timeout=3) as r:
            body = r.read().decode("utf-8", "replace")
        if '"ok":true' in body.replace(" ", ""):
            tmp = p.last_send + ".%d.tmp" % os.getpid()
            with open(tmp, "w", encoding="utf-8") as f:
                f.write(repr(time.time()))
            os.replace(tmp, p.last_send)
        else:
            _tlog(p, "send-FAIL", body[:80])
    except Exception as e:
        _tlog(p, "send-FAIL", type(e).__name__)


def loop(p, sender=send_typing, sleep=time.sleep):
    my_pid = os.getpid()
    for _ in range(20):           # the lease names our pid a few ms after Popen
        if (_read(p) or {}).get("pid") == my_pid:
            break
        sleep(0.1)
    else:
        return
    sends = 0
    while True:
        try:
            with open(p.inflight, "w") as f:
                f.write(str(my_pid))
        except Exception:
            pass
        try:
            state, lease = _loop_state(p, my_pid)
            if not state:
                break
            if state == "send":
                sender(p, lease["chat_id"], lease.get("thread_id"))
                sends += 1
        finally:
            try:
                os.remove(p.inflight)
            except Exception:
                pass
        stopped = False
        for _ in range(SEND_EVERY):
            sleep(1)
            if not _loop_state(p, my_pid)[0]:
                stopped = True
                break
        if stopped:
            break
    _tlog(p, "LOOP-END", f"sends={sends}")



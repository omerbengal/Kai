def parse_open(prompt, group_id, own_topic=None, own_username=None):
    """(chat_id, thread_id, msg_id) of the first channel message that should show typing, else None.
    A General message (a tag from main Kai, stage 3) types in the bot's own topic, where the work happens."""
    for m in re.finditer(r"<channel([\s\S]*?)>", prompt or ""):
        attrs = m.group(1)

        def attr(n):
            a = re.search(rf'\b{n}="(.*?)"', attrs, re.DOTALL)
            return a.group(1) if a else None
        if "telegram" not in (attr("source") or "") or attr("event_type") == "reaction":
            continue
        chat = attr("chat_id")
        if chat not in {str(group_id), OMER_DM}:
            continue
        if attr("user_id") in _other_bot_ids() and (attr("message_thread_id") or attr("reply_to_message_id")):
            continue   # another bot's answer / chatter (bot-to-bot, 06/11/2026): no work starts, no typing
        thread = attr("message_thread_id")
        body = (prompt[m.end():].split("</channel>", 1)[0]).lower()
        if not thread and chat == str(group_id) and "@nova_personalassistant_bengi_bot" in body \
                and not (own_username and f"@{own_username.lower()}" in body):
            continue   # Omer tagged main Kai in General (08/11/2026): main's work, this bot never types
        if not thread and chat == str(group_id) and own_username \
                and attr("user_id") in (_other_bot_ids() | {MAIN_BOT_ID}) \
                and f"@{own_username.lower()}" not in body:
            continue   # another bot's General message not addressed to this bot (main Kai's own ACK, 15/11)
        if not thread and chat == str(group_id) and own_topic:
            thread = str(own_topic)
        return chat, thread, attr("message_id")
    return None


def _arg(argv, flag, default=None):
    return argv[argv.index(flag) + 1] if flag in argv else default


def main(argv):
    cmd = argv[1] if len(argv) > 1 else ""
    bot = _arg(argv, "--bot")
    if not bot:
        return 0
    try:
        p = Paths(bot)
        if cmd == "loop":
            loop(p)
            return 0
        data = {}
        if cmd in ("open", "renew", "pause", "post"):
            try:
                data = json.loads(sys.stdin.buffer.read().decode("utf-8", errors="replace") or "{}")
            except Exception:
                data = {}
        if cmd == "open":
            import kai_bots
            bcfg = kai_bots.bot(bot)
            hit = parse_open(data.get("prompt", "") or data.get("content", ""), bcfg.get("group_id"),
                             own_topic=(bcfg.get("topics") or [None])[0], own_username=bcfg.get("username"))
            if hit:
                open_lease(p, hit[0], hit[1], msg_id=hit[2])
        elif cmd == "renew":
            if (data.get("tool_name") or "") not in SKIP_TOOLS:
                renew(p, hold=int(_arg(argv, "--hold", LEASE_SECONDS)))
            open_call(p, data.get("tool_use_id"), data.get("tool_name") or "", data.get("tool_input"))
            if is_bg_call(data.get("tool_name"), data.get("tool_input")):
                mark_bg(p, data.get("agent_id"), data.get("transcript_path"), data.get("session_id"))
        elif cmd == "pause":
            ti = data.get("tool_input") or {}
            pause(p, wait_expire="--react" in argv, reply_to=ti.get("reply_to") or ti.get("message_id"),
                  text=ti.get("text"))
        elif cmd == "post":
            close_call(p, data.get("tool_use_id"))
        elif cmd == "attach":   # link a manually sent ACK to its task by hand
            attach_ack(p, _arg(argv, "--msg"), _arg(argv, "--ack"))
            print("ok")
        elif cmd == "end-turn":
            _tlog(p, "TURN-END", "lease left to expire")
    except Exception as e:  # a hook must never break the session
        print(f"[bot_typing] {cmd} failed: {type(e).__name__}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

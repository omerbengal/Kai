#!/usr/bin/env python
"""Typing indicator for a Kai domain bot - a per-bot port of scripts/typing_lease.py (05/11/2026).

Omer (msg 22485): the bots' "typing" stopped ~1.5s after the auto-ACK. The only typing they had was the
plugin's single sendChatAction on arrival, which the client clears as soon as the ACK message lands.

Same lease model as main Kai (investigation #043), but every bit of state is the bot's own:
  state     <home>/tmp/typing_lease.json (+ .lock, inflight, last_send)  - never D:/Kai/tmp
  token     the bot's own, from <state_dir>/.env (bot_tg.token)          - never main Kai's
  target    chat_id + message_thread_id of the message being handled (sendChatAction in a forum topic)

Hooks (generated by bots/new_bot.py into every bot's settings.json):
  UserPromptSubmit         open   - only an incoming message from this bot's group / Omer's DM opens it
  PreToolUse reply         pause  - typing off before the message is sent (waits for an in-flight send)
  PreToolUse react         pause --react - also waits until client-side typing has expired
  PreToolUse Agent         renew --hold 60 - a background worker takes up to ~55s to make its first call
  PreToolUse * (others)    renew  - every tool call, dispatcher or background worker, keeps it alive
  Stop                     end-turn - does NOT drop the lease (unlike main Kai): a bot's dispatcher ends its
                           turn right after spawning a background worker, and the worker's calls must keep
                           renewing. The lease expires by itself LEASE_SECONDS after the last tool call.

Parallel tasks (Omer msg 22497): a bot can work on two messages at once (two workers). One lease, but it
counts the open TASKS: every incoming message opens one (keyed by its message id, with its chat / topic), the
auto-ACK attaches its ACK id, and `bot_tg.py delete` of that ACK (the end of every task) closes it. A reply
pauses typing for the reply itself; closing a task resumes typing at once if another task is still open, and
while tasks are open a tool call PAUSE_RESUME seconds after a pause (not RESUME_GRACE) revives it. Open tasks
also keep typing alive between tool calls (a long Bash call) for up to ACTIVITY_WINDOW since the last tool
call. A task with no ACK (trivial message) closes on a reply to it; a task older than TASK_TTL is dropped.

Never call this by hand from a model; the hooks own it (principle 11).
"""
import json
import os
import re
import subprocess
import sys
import time
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, "D:/Kai/scripts")
try:
    import net_ipv4  # noqa: F401  IPv6 to api.telegram.org is slow on this PC
except Exception:
    pass

LEASE_SECONDS = 15
AGENT_HOLD = 60          # renew --hold: background worker spawn gap
RESUME_GRACE = 10        # after a pause, renew() cannot revive typing for this long
INFLIGHT_WAIT = 3.5
TYPING_VISIBLE = 5.5
SEND_EVERY = 4
PAUSE_RESUME = 8         # open tasks remain: a tool call this long after a pause revives typing
ACTIVITY_WINDOW = 60     # open tasks keep typing alive this long after the last tool call
TASK_TTL = 1800          # a task never closed (crashed worker) stops counting after 30 min
NOACK_TTL = 120          # a task without an ACK (trivial message, answered by a react) after 2 min
SKIP_TOOLS = ("mcp__plugin_telegram_telegram__reply", "mcp__plugin_telegram_telegram__react")
OMER_DM = os.environ.get("KAI_TELEGRAM_CHAT_ID", "")
DETACHED_PROCESS = 0x00000008
CREATE_NEW_PROCESS_GROUP = 0x00000200
CREATE_NO_WINDOW = 0x08000000


class Paths:
    def __init__(self, bot, home=None):
        self.bot = bot
        if home is None:
            import kai_bots
            home = kai_bots.bot(bot)["home"]
        self.dir = os.path.join(home, "tmp")
        self.lease = os.path.join(self.dir, "typing_lease.json")
        self.lock = self.lease + ".lock"
        self.inflight = os.path.join(self.dir, "typing_inflight.txt")
        self.last_send = os.path.join(self.dir, "typing_last_send.txt")
        self.trace = os.path.join(self.dir, "typing_trace.log")


def _tlog(p, event, extra=""):
    try:
        import datetime
        with open(p.trace, "a", encoding="utf-8") as f:
            f.write("{}  {:<12} {}\n".format(datetime.datetime.now().strftime("%H:%M:%S.%f")[:-3], event, extra))
    except Exception:
        pass


def _read(p):
    try:
        with open(p.lease, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


def _write(p, lease):
    os.makedirs(p.dir, exist_ok=True)
    tmp = p.lease + ".%d.tmp" % os.getpid()
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(lease, f)
    os.replace(tmp, p.lease)


class _Lock:
    """O_EXCL lock file; stale after 2s; gives up after 1s (typing must never block a tool)."""
    def __init__(self, p):
        self.path, self.fd = p.lock, None
        os.makedirs(p.dir, exist_ok=True)

    def __enter__(self):
        end = time.time() + 1.0
        while True:
            try:
                self.fd = os.open(self.path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                return self
            except FileExistsError:
                try:
                    if time.time() - os.path.getmtime(self.path) > 2:
                        os.remove(self.path)
                        continue
                except Exception:
                    pass
                if time.time() > end:
                    return self
                time.sleep(0.02)
            except Exception:
                return self

    def __exit__(self, *a):
        if self.fd is not None:
            try:
                os.close(self.fd)
                os.remove(self.path)
            except Exception:
                pass


def _alive(pid):
    try:
        import psutil
        return psutil.pid_exists(int(pid))
    except Exception:
        return False


def _spawn_loop(p):
    proc = subprocess.Popen(
        [sys.executable, os.path.abspath(__file__), "loop", "--bot", p.bot],
        creationflags=DETACHED_PROCESS | CREATE_NEW_PROCESS_GROUP | CREATE_NO_WINDOW,
        close_fds=True, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return proc.pid


def _ensure_loop(p, lease, spawn):
    if lease.get("pid") and _alive(lease["pid"]):
        return lease
    lease["pid"] = spawn(p)
    return lease


def _tasks(lease, now=None):
    """Open tasks, without the ones older than TASK_TTL."""
    now = now or time.time()
    t = lease.get("tasks") or {}
    return {k: v for k, v in t.items()
            if now - float(v.get("opened", 0) or 0) < (TASK_TTL if v.get("ack") else NOACK_TTL)}


def _keepalive(lease, now=None):
    now = now or time.time()
    return bool(_tasks(lease, now)) and now - float(lease.get("last_activity", 0) or 0) < ACTIVITY_WINDOW


def _resume(p, lease, spawn, now):
    tasks = _tasks(lease, now)
    if tasks:   # type where a still-open task lives (the newest one)
        last = max(tasks.values(), key=lambda v: float(v.get("opened", 0) or 0))
        if last.get("chat_id"):
            lease["chat_id"], lease["thread_id"] = last.get("chat_id"), last.get("thread_id")
    lease["paused_at"] = 0
    lease["last_activity"] = now
    lease["deadline"] = max(float(lease.get("deadline", 0) or 0), now + LEASE_SECONDS)
    return _ensure_loop(p, lease, spawn)


def open_lease(p, chat_id, thread_id=None, spawn=_spawn_loop, msg_id=None):
    """Incoming message: the ONLY thing that opens the indicator (and clears a pause). Opens a task."""
    now = time.time()
    with _Lock(p):
        old = _read(p) or {}
        tasks = _tasks(old, now)
        if msg_id:
            prev = tasks.get(str(msg_id), {})
            tasks[str(msg_id)] = {"chat_id": str(chat_id), "thread_id": str(thread_id) if thread_id else None,
                                  "opened": now, "ack": prev.get("ack")}
        lease = {"chat_id": str(chat_id), "thread_id": str(thread_id) if thread_id else None,
                 "deadline": now + LEASE_SECONDS, "turn_open": True, "pid": old.get("pid", 0),
                 "paused_at": 0, "last_activity": now, "tasks": tasks}
        lease = _ensure_loop(p, lease, spawn)
        _write(p, lease)
    _tlog(p, "OPEN", f"chat={chat_id} thread={thread_id} msg={msg_id} tasks={len(tasks)}")


def attach_ack(p, msg_id, ack_id):
    """auto-ACK sent: remember which ACK belongs to which task (its delete ends the task)."""
    with _Lock(p):
        # no lease yet: the async open hook may still be running (it keeps this entry), or the bot has no
        # typing hooks at all - turn_open False, so nothing can start typing from here
        lease = _read(p) or {"tasks": {}, "deadline": 0, "turn_open": False, "pid": 0, "paused_at": 0}
        tasks = lease.setdefault("tasks", {})
        t = tasks.setdefault(str(msg_id), {"opened": time.time()})
        t["ack"] = str(ack_id)
        _write(p, lease)


def end_task(p, ack_id=None, msg_id=None, spawn=_spawn_loop):
    """A task finished (its ACK deleted, or a reply to a task with no ACK). Typing resumes at once if
    another task is still open. Returns the number of tasks left."""
    now = time.time()
    with _Lock(p):
        lease = _read(p)
        if not lease:
            return 0
        tasks = _tasks(lease, now)
        gone = [k for k, v in tasks.items()
                if (ack_id and str(v.get("ack")) == str(ack_id)) or (msg_id and k == str(msg_id))]
        if not gone:
            return len(tasks)
        for k in gone:
            tasks.pop(k, None)
        lease["tasks"] = tasks
        if tasks and lease.get("turn_open"):
            lease = _resume(p, lease, spawn, now)
        _write(p, lease)
    _tlog(p, "TASK-END", f"ack={ack_id} msg={msg_id} left={len(tasks)}")
    return len(tasks)


def renew(p, hold=LEASE_SECONDS, spawn=_spawn_loop):
    """Extend an open lease. Never opens one; never revives a pause younger than RESUME_GRACE."""
    now = time.time()
    with _Lock(p):
        lease = _read(p)
        if not lease or not lease.get("turn_open"):
            return False
        lease["last_activity"] = now
        paused_at = float(lease.get("paused_at", 0) or 0)
        # another task still open = the pause was for another task's reply: short grace only
        grace = PAUSE_RESUME if _tasks(lease, now) else RESUME_GRACE
        if paused_at and now - paused_at < grace:
            _write(p, lease)
            return False
        lease = _resume(p, lease, spawn, now)
        lease["deadline"] = max(float(lease.get("deadline", 0) or 0), now + hold)
        _write(p, lease)
        return True


def _last_send(p):
    try:
        with open(p.last_send, encoding="utf-8") as f:
            return float(f.read().strip() or 0)
    except Exception:
        return 0.0


def pause(p, wait_expire=False, reply_to=None):
    """Before a reply / react: typing off now; returns after any in-flight sendChatAction landed.
    A reply to a task that has no ACK (trivial / inline) is that task's end."""
    had = False
    with _Lock(p):
        lease = _read(p)
        if lease:
            had = True
            lease["deadline"] = 0
            lease["paused_at"] = time.time()
            if reply_to:
                t = (lease.get("tasks") or {}).get(str(reply_to))
                if t is not None and not t.get("ack"):
                    lease["tasks"].pop(str(reply_to), None)
            _write(p, lease)
    end = time.time() + INFLIGHT_WAIT
    while time.time() < end:
        try:
            if time.time() - os.path.getmtime(p.inflight) > INFLIGHT_WAIT + 1:
                break
        except Exception:
            break
        time.sleep(0.02)
    if wait_expire and had:
        remaining = _last_send(p) + TYPING_VISIBLE - time.time()
        if remaining > 0:
            time.sleep(min(remaining, TYPING_VISIBLE))
    _tlog(p, "PAUSE", "react" if wait_expire else "")


def _lease_alive(p, my_pid):
    lease = _read(p)
    if not lease or int(lease.get("pid", 0) or 0) != my_pid:
        return None
    now = time.time()
    if float(lease.get("deadline", 0) or 0) > now:
        return lease
    if not lease.get("paused_at") and _keepalive(lease, now):
        return lease   # open tasks, a long tool call in progress
    return None


def send_typing(p, chat_id, thread_id=None):
    import bot_tg
    params = {"chat_id": chat_id, "action": "typing"}
    if thread_id:
        params["message_thread_id"] = thread_id
    url = f"https://api.telegram.org/bot{bot_tg.token(p.bot)}/sendChatAction"
    try:
        with urllib.request.urlopen(url, data=urllib.parse.urlencode(params).encode(), timeout=3) as r:
            body = r.read().decode("utf-8", "replace")
        if '"ok":true' in body.replace(" ", ""):
            tmp = p.last_send + ".%d.tmp" % os.getpid()
            with open(tmp, "w", encoding="utf-8") as f:
                f.write(repr(time.time()))
            os.replace(tmp, p.last_send)
        else:
            _tlog(p, "send-FAIL", body[:80])
    except Exception as e:
        _tlog(p, "send-FAIL", type(e).__name__)


def loop(p, sender=send_typing, sleep=time.sleep):
    my_pid = os.getpid()
    for _ in range(20):           # the lease names our pid a few ms after Popen
        if (_read(p) or {}).get("pid") == my_pid:
            break
        sleep(0.1)
    else:
        return
    sends = 0
    while True:
        try:
            with open(p.inflight, "w") as f:
                f.write(str(my_pid))
        except Exception:
            pass
        try:
            lease = _lease_alive(p, my_pid)
            if not lease:
                break
            sender(p, lease["chat_id"], lease.get("thread_id"))
            sends += 1
        finally:
            try:
                os.remove(p.inflight)
            except Exception:
                pass
        stopped = False
        for _ in range(SEND_EVERY):
            sleep(1)
            if not _lease_alive(p, my_pid):
                stopped = True
                break
        if stopped:
            break
    _tlog(p, "LOOP-END", f"sends={sends}")


def parse_open(prompt, group_id):
    """(chat_id, thread_id) of the first channel message that should show typing, else None."""
    for m in re.finditer(r"<channel([\s\S]*?)>", prompt or ""):
        attrs = m.group(1)

        def attr(n):
            a = re.search(rf'\b{n}="(.*?)"', attrs, re.DOTALL)
            return a.group(1) if a else None
        if "telegram" not in (attr("source") or "") or attr("event_type") == "reaction":
            continue
        chat = attr("chat_id")
        if chat not in {str(group_id), OMER_DM}:
            continue
        return chat, attr("message_thread_id"), attr("message_id")
    return None


def _arg(argv, flag, default=None):
    return argv[argv.index(flag) + 1] if flag in argv else default


def main(argv):
    cmd = argv[1] if len(argv) > 1 else ""
    bot = _arg(argv, "--bot")
    if not bot:
        return 0
    try:
        p = Paths(bot)
        if cmd == "loop":
            loop(p)
            return 0
        data = {}
        if cmd in ("open", "renew", "pause"):
            try:
                data = json.loads(sys.stdin.buffer.read().decode("utf-8", errors="replace") or "{}")
            except Exception:
                data = {}
        if cmd == "open":
            import kai_bots
            hit = parse_open(data.get("prompt", "") or data.get("content", ""), kai_bots.bot(bot).get("group_id"))
            if hit:
                open_lease(p, hit[0], hit[1], msg_id=hit[2])
        elif cmd == "renew":
            if (data.get("tool_name") or "") not in SKIP_TOOLS:
                renew(p, hold=int(_arg(argv, "--hold", LEASE_SECONDS)))
        elif cmd == "pause":
            ti = data.get("tool_input") or {}
            pause(p, wait_expire="--react" in argv, reply_to=ti.get("reply_to") or ti.get("message_id"))
        elif cmd == "end-turn":
            _tlog(p, "TURN-END", "lease left to expire")
    except Exception as e:  # a hook must never break the session
        print(f"[bot_typing] {cmd} failed: {type(e).__name__}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
